/** Все пороги в одном месте. В интерфейсе их нет. */
object Config {
    /** Ниже этой скорости считаем, что машина стоит (или я иду пешком). */
    const val STOP_SPEED_KMH = 8.0

    /** После «конца» поездки быстрее этого — значит, я снова поехал. */
    const val RESUME_SPEED_KMH = 25.0

    /** «Рядом с целью» — ближе этого расстояния. */
    const val NEAR_TARGET_M = 200.0

    /** Сколько стоять рядом с целью, чтобы поездка закончилась. */
    const val NEAR_TARGET_STOP_MS = 2 * 60_000L

    /** Сколько стоять в любом другом месте, чтобы поездка закончилась. */
    const val STOP_END_MS = 10 * 60_000L

    /** Сколько ещё слушать GPS после конца: вдруг поеду дальше (пробка, очередь). */
    const val RESUME_WINDOW_MS = 30 * 60_000L

    /** Точки GPS с точностью хуже этой отбрасываем. */
    const val MAX_ACCURACY_M = 30f

    /** Сдвиги меньше этого — дрожание GPS, в км не идут. */
    const val MIN_STEP_M = 10.0

    /** Пока машина стоит, сдвиг засчитываем, только если он больше этого (медленная пробка). */
    const val CRAWL_STEP_M = 50.0

    /** Быстрее этого машина не ездит — значит, это «прыжок» GPS. */
    const val MAX_JUMP_SPEED_KMH = 250.0

    /** Пауза между точками длиннее этого — GPS пропал, а не «стоял». */
    const val MAX_STOP_GAP_MS = 30_000L

    /** Поездки короче этого не сохраняем (нажал случайно). */
    const val MIN_TRIP_M = 100.0

    /** Точка ближе этого к адресу кнопки — пишем название кнопки («Дом»). */
    const val PLACE_RADIUS_M = 200.0



    /** Средняя скорость в движении до этой — город (расход «в городе»). */
    const val CITY_SPEED_KMH = 40.0

    /** От этой — трасса (расход «за городом»). Между — плавно. */
    const val HIGHWAY_SPEED_KMH = 80.0

    /** Автозапись, запасной канал: как часто Android сообщает, чем ты занят. */
    const val AUTO_SAMPLE_MS = 90_000L

    /** Автозапись: насколько Android должен быть уверен, что ты «в машине» (0–100). */
    const val AUTO_MIN_CONFIDENCE = 75

    /** Проверка «правда едем»: две примерные точки должны быть не ближе по времени, чем это… */
    const val MOVE_MIN_GAP_MS = 45_000L

    /** …и не дальше, чем это. */
    const val MOVE_MAX_GAP_MS = 6 * 60_000L

    /** Сдвинулся меньше — не едем (ходишь дома, точка по Wi‑Fi «гуляет»). */
    const val MOVE_MIN_DISTANCE_M = 400.0

    /** Скорость между точками ниже этой — не машина. */
    const val MOVE_MIN_SPEED_KMH = 15.0

    /** Геолокация выключена — спросить, только если «в машине» столько раз подряд. */
    const val AUTO_STREAK_WITHOUT_LOCATION = 3

    /** Событие «сел в машину» старше этого — устарело, не верим. */
    const val AUTO_EVENT_MAX_AGE_MS = 3 * 60_000L


    /** Вопрос «Едешь на своём авто?» висит столько, потом исчезает сам. */
    const val ASK_TIMEOUT_MS = 30 * 60_000L

    /** После «НЕТ» не спрашивать снова столько времени (автобус, такси). */
    const val AUTO_MUTE_AFTER_NO_MS = 30 * 60_000L

    /** После «Стоп» вручную не начинать автозапись столько времени. */
    const val AUTO_MUTE_AFTER_STOP_MS = 20 * 60_000L


    /** Как часто просим у GPS новую точку. */
    const val GPS_INTERVAL_MS = 1_000L

    /** Как часто проверяем таймеры остановки, даже если новых точек нет. */
    const val TICK_MS = 10_000L
}
